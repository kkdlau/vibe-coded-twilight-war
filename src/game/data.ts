export function getWeaponSwapDuration(kind: GunKind | MeleeKind): number {
  switch (kind) {
    case 'claw':
      return 0.16;
    case 'pistol':
      return 0.2;
    case 'knife':
      return 0.24;
    case 'rifle':
      return 0.34;
    case 'shotgun':
      return 0.42;
    case 'sniper':
      return 0.48;
    case 'greatsword':
      return 0.54;
    case 'shield':
      return 0.44;
  }
}

export function getReputationQiMultiplier(reputation: number): number {
  const rep = Math.max(0, reputation);
  if (rep <= 0) return 0.5;
  return 0.5 + 0.5 * Math.log10(Math.max(1, rep));
}

